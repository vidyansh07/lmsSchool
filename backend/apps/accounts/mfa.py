from apps.common.models import BaseModel

#: RFC 6238 defaults. Not policy-driven: changing the step size would desync
#: every already-enrolled authenticator app, which is not a knob an
#: administrator should be able to turn from a settings screen.
TOTP_STEP_SECONDS = 30
TOTP_DIGITS = 6
TOTP_VALID_WINDOW = 1  # ± one step either side of "now"
TOTP_ISSUER = "Grras LMS"

#: Fixed by ADR-05 ("Pending state expires in 5 min"), not a policy: this is
#: a property of the login flow itself, not an institution's risk appetite.
PENDING_SESSION_KEY = "mfa_pending"
PENDING_TTL_SECONDS = 5 * 60

RECOVERY_CODE_COUNT = 10


class MfaMethod(models.TextChoices):
    """The three ways a pending sign-in or a step-up may be proved."""

    TOTP = "totp", _("Authenticator app")
    EMAIL = "email", _("Email code")
    RECOVERY = "recovery", _("Recovery code")


class MfaEnrolmentConflict(ConflictError):
    default_detail = "MFA is already enabled. Disable it before enrolling a new device."
    default_code = "mfa_already_enrolled"


class MfaNoPendingEnrolment(ApplicationError):
    default_detail = "Start enrolment before confirming a code."
    default_code = "mfa_no_pending_enrolment"


class MfaNotEnabled(ApplicationError):
    default_detail = "MFA is not enabled on this account."
    default_code = "mfa_not_enabled"


class InvalidMfaCode(ApplicationError):
    """The one failure shape every method answers with.

    Deliberately generic (SECURITY_DECISIONS: never reveal, via message or
    timing, which mechanism specifically failed): a wrong TOTP code, an
    expired email code, an already-used recovery code and "no device at all"
    all reach the API caller as this same 400.
    """

    default_detail = "That code is not right or has expired."
    default_code = "invalid_code"


