# Pending-MFA session state
# ---------------------------------------------------------------------------


def start_pending(*, request, user) -> None:
    """Stamp the session as pending. ``django.contrib.auth.login`` is
    deliberately never called here — see the module docstring for why that
    alone is what keeps every other endpoint closed to this session."""
    request.session[PENDING_SESSION_KEY] = {
        "user_id": str(user.pk),
        "expires_at": (timezone.now() + timedelta(seconds=PENDING_TTL_SECONDS)).timestamp(),
    }
    request.session.modified = True


def get_pending_user(*, request) -> Any:
    """The user a pending session names, or ``None`` if there is no pending
    session, it has expired, or it names an account that no longer
    qualifies (deactivated, deleted) — any of which clears the marker."""
    data = request.session.get(PENDING_SESSION_KEY)
    if not isinstance(data, dict):
        return None
    expires_at = data.get("expires_at")
    if not expires_at or float(expires_at) < timezone.now().timestamp():
        clear_pending(request=request)
        return None

    from .models import User

    try:
        return User.objects.get(pk=data.get("user_id"), is_active=True)
    except (User.DoesNotExist, DjangoValidationError, ValueError, TypeError):
        clear_pending(request=request)
        return None


def clear_pending(*, request) -> None:
    if PENDING_SESSION_KEY in request.session:
        del request.session[PENDING_SESSION_KEY]
        request.session.modified = True


