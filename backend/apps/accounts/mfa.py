# Models
# ---------------------------------------------------------------------------


class MfaDevice(BaseModel):
    """A user's TOTP device. One per user (``OneToOneField``).

    Not soft-deletable, and disable/re-enrol genuinely delete/overwrite the
    row rather than flag it — see the module docstring on why a "restorable"
    MFA artifact would be a vulnerability, not a convenience (same precedent
    as ``OneTimeCode``, which is also plain ``BaseModel``).

    An unconfirmed device (``confirmed_at`` is ``None``) is inert: it never
    counts toward "this user has MFA", is never offered as a login method,
    and is silently replaced by the next call to :func:`start_enrolment` —
    exactly the shape of "I scanned the QR code but never entered a code",
    which should cost the user nothing to retry.
    """

    user = models.OneToOneField(
        "accounts.User", on_delete=models.CASCADE, related_name="mfa_device"
    )
    secret_encrypted = models.BinaryField()
    confirmed_at = models.DateTimeField(null=True, blank=True)
    #: Replay guard (SECURITY_DECISIONS "MFA"). The last TOTP step accepted;
    #: anything at or before it is refused, confirmed or not.
    last_used_step = models.BigIntegerField(null=True, blank=True)
    name = models.CharField(max_length=60, default="Authenticator app")

    class Meta:
        verbose_name = _("MFA device")
        verbose_name_plural = _("MFA devices")

    def __str__(self) -> str:
        # Never the secret, encrypted or otherwise.
        state = "confirmed" if self.confirmed_at else "pending"
        return f"TOTP device for {self.user_id} ({state})"

    @property
    def is_confirmed(self) -> bool:
        return self.confirmed_at is not None


class RecoveryCode(BaseModel):
    """One single-use recovery code. Ten are issued together and share a
    "generation" only in the sense that :func:`issue_recovery_codes` deletes
    every prior row for the user before creating the new ten."""

    user = models.ForeignKey(
        "accounts.User", on_delete=models.CASCADE, related_name="recovery_codes"
    )
    code_hash = models.CharField(max_length=64, editable=False)
    used_at = models.DateTimeField(null=True, blank=True)

    class Meta:
        verbose_name = _("recovery code")
        verbose_name_plural = _("recovery codes")
        indexes = [
            models.Index(fields=["user", "used_at"], name="recovery_user_used_idx"),
        ]

    def __str__(self) -> str:
        # Never the code or its hash.
        state = "used" if self.used_at else "unused"
        return f"Recovery code for {self.user_id} ({state})"


# ---------------------------------------------------------------------------
# Encryption
# ---------------------------------------------------------------------------


def _fernet() -> Fernet:
    key = getattr(settings, "MFA_ENCRYPTION_KEY", "") or ""
    if not key:
        # Defence in depth: `config/settings/hardened.py` already refuses to
        # boot a deployed environment without this, so reaching here means a
        # programming error in a settings module, not a request an attacker
        # can trigger. Fails closed either way.
        raise ImproperlyConfigured(
            "MFA_ENCRYPTION_KEY is not configured. See docs/environments.md."
        )
    return Fernet(key.encode("utf-8") if isinstance(key, str) else key)


def encrypt_secret(raw_secret: str) -> bytes:
    return _fernet().encrypt(raw_secret.encode("utf-8"))


def decrypt_secret(token: bytes) -> str | None:
    """Returns ``None`` rather than raising on a token that will not decrypt
    (a corrupted row, a rotated key) — a request to verify a TOTP code should
    answer "wrong code", not crash, for a fault that is the deployment's,
    never the caller's, to fix."""
    try:
        return _fernet().decrypt(bytes(token)).decode("utf-8")
    except InvalidToken:
        return None


# ---------------------------------------------------------------------------
# TOTP
# ---------------------------------------------------------------------------


def generate_totp_secret() -> str:
    return pyotp.random_base32()


def provisioning_uri(*, user, secret: str) -> str:
    """The ``otpauth://`` URI an authenticator app scans as a QR code."""
    totp = pyotp.TOTP(secret, digits=TOTP_DIGITS, interval=TOTP_STEP_SECONDS)
    return totp.provisioning_uri(name=user.email, issuer_name=TOTP_ISSUER)


def qr_svg(data: str) -> str:
    """``data`` rendered as an SVG QR code.

    Uses ``qrcode`` (already a dependency — ``apps.certificates.rendering``
    renders certificate-verification QR codes with the same library, as PNG)
    with its SVG image factory, so this adds no new dependency. SVG rather
    than PNG: the secret never touches disk as an image file, the string is
    small enough to return inline in the JSON response, and it scales
    cleanly in a modal at any size the frontend chooses.
    """
    import qrcode
    from qrcode.image.svg import SvgPathImage

    code = qrcode.QRCode(image_factory=SvgPathImage, box_size=8, border=2)
    code.add_data(data)
    code.make(fit=True)
    buffer = BytesIO()
    code.make_image().save(buffer)
    return buffer.getvalue().decode("utf-8")


def _current_step(at) -> int:
    return int(at.timestamp() // TOTP_STEP_SECONDS)


def _matched_step(*, secret: str, code: str, last_used_step: int | None) -> int | None:
    """The TOTP step ``code`` matches, or ``None``.

    Checks "now" and one step either side (``TOTP_VALID_WINDOW``), refusing
    any step at or before ``last_used_step`` — the replay guard applies
    before comparison, not after, so an already-spent code can never match
    twice even if the clock skew window would otherwise let it.
    """
    submitted = (code or "").strip()
    if not submitted:
        return None
    totp = pyotp.TOTP(secret, digits=TOTP_DIGITS, interval=TOTP_STEP_SECONDS)
    now = timezone.now()
    now_step = _current_step(now)
    floor = -1 if last_used_step is None else int(last_used_step)
    for offset in (0, -1, 1):
        step = now_step + offset
        if step <= floor:
            continue
        candidate = totp.at(now, counter_offset=offset)
        if pyotp.utils.strings_equal(candidate, submitted):
            return step
    return None


@transaction.atomic
def verify_totp_code(*, user, code: str) -> bool:
    """Check ``code`` against the user's confirmed device, if any.

    ``select_for_update`` on the device row: two concurrent verifications of
    the same step cannot both read the old ``last_used_step``, so both
    succeeding — the same replay ``verify_email_code`` already guards
    against for email codes — is not possible here either.
    """
    device = (
        MfaDevice.objects.select_for_update().filter(user=user, confirmed_at__isnull=False).first()
    )
    if device is None:
        return False
    secret = decrypt_secret(bytes(device.secret_encrypted))
    if secret is None:
        return False
    step = _matched_step(secret=secret, code=code, last_used_step=device.last_used_step)
    if step is None:
        return False
    device.last_used_step = step
    device.save(update_fields=["last_used_step", "updated_at"])
    return True


# ---------------------------------------------------------------------------
# Recovery codes
# ---------------------------------------------------------------------------

_RECOVERY_CODE_CLEAN_RE = re.compile(r"[^A-Z0-9]")


def _normalise_recovery_code(raw: str) -> str:
    return _RECOVERY_CODE_CLEAN_RE.sub("", (raw or "").upper())


def _hash_recovery_code(normalised: str) -> str:
    return sha256(normalised.encode("utf-8")).hexdigest()


def _generate_recovery_code() -> str:
    """Ten hex characters (40 bits), grouped for readability. Single-use and
    rate-limited by the same ``auth`` throttle as every other MFA guess, so
    this is comfortably past the point where brute force is the weak link."""
    raw = secrets.token_hex(5).upper()
    return f"{raw[:5]}-{raw[5:]}"


def issue_recovery_codes(*, user) -> list[str]:
    """Ten fresh codes, replacing (invalidating) every prior one.

    Deletes outright rather than soft-deleting — see the module and model
    docstrings: a recovery code that could be un-deleted back into validity
    would be a genuine MFA bypass, not a recoverable mistake.
    """
    RecoveryCode.objects.filter(user=user).delete()
    plain_codes: list[str] = []
    rows: list[RecoveryCode] = []
    for _index in range(RECOVERY_CODE_COUNT):
        plain = _generate_recovery_code()
        plain_codes.append(plain)
        rows.append(
            RecoveryCode(user=user, code_hash=_hash_recovery_code(_normalise_recovery_code(plain)))
        )
    RecoveryCode.objects.bulk_create(rows)
    return plain_codes


@transaction.atomic
def consume_recovery_code(*, user, code: str) -> bool:
    """Check and burn one recovery code. ``select_for_update`` plus the
    ``used_at__isnull=True`` filter is exactly ``verify_email_code``'s
    concurrency shape: a second simultaneous submission of the same code
    blocks on the row lock, then finds it already used."""
    normalised = _normalise_recovery_code(code)
    if not normalised:
        return False
    hashed = _hash_recovery_code(normalised)
    row = (
        RecoveryCode.objects.select_for_update()
        .filter(user=user, code_hash=hashed, used_at__isnull=True)
        .first()
    )
    if row is None:
        return False
    row.used_at = timezone.now()
    row.save(update_fields=["used_at", "updated_at"])
    return True


# ---------------------------------------------------------------------------
# Dispatch: one entry point login and step-up both call
# ---------------------------------------------------------------------------


def verify(*, user, method: str, code: str, purpose: str, request_ip: str | None = None) -> bool:
    """Check ``code`` by ``method`` for ``user``. ``purpose`` is ``"login"``
    or ``"step_up"`` and only matters for the email method, which reuses
    Phase 4's ``OneTimeCode`` and needs to know which of its two reserved
    purposes this is."""
    if method == MfaMethod.TOTP:
        return verify_totp_code(user=user, code=code)
    if method == MfaMethod.RECOVERY:
        return consume_recovery_code(user=user, code=code)
    if method == MfaMethod.EMAIL:
        from .otp import OtpPurpose, verify_email_code

        otp_purpose = OtpPurpose.LOGIN if purpose == "login" else OtpPurpose.STEP_UP
        return verify_email_code(user=user, purpose=otp_purpose, code=code, request_ip=request_ip)
    return False


