"""Multi-factor authentication (ERP Phase 5, ADR-05): TOTP, recovery codes,
and the pending-MFA sign-in state.

Builds directly on Phase 4's :mod:`apps.accounts.otp` rather than duplicating
it: email is still one of the three factors here, and it is still
``OneTimeCode`` underneath — this module passes ``purpose="login"`` (reserved
for exactly this by Phase 4) or ``purpose="step_up"`` and otherwise leaves
that model alone. Sits beside :mod:`apps.accounts.otp` and
:mod:`apps.accounts.stepup`, not inside ``services.py``, for the same reason
those two do (see their module docstrings): the views call these functions
directly, so a serializer or a view is never where the decision "is this code
right" gets made.

Two more mechanisms this module owns:

* **TOTP** (RFC 6238, 30-second step, ±1 step tolerance). The shared secret
  is generated by :mod:`pyotp`, encrypted at rest with ``Fernet`` under
  ``settings.MFA_ENCRYPTION_KEY`` (environment-only, no production default —
  see ``config/settings/hardened.py``), and never appears in a log line, an
  audit row or an API response after the one enrolment call that hands it to
  the user. Replay of an already-accepted step (or anything before it) is
  refused by remembering ``MfaDevice.last_used_step``.
* **Recovery codes.** Ten single-use codes, hashed the same way
  ``OneTimeCode`` hashes its codes (SHA-256, no per-row salt needed — these
  are high-entropy random strings, not 6-digit codes, so there is nothing a
  rainbow table gains from a shared hash function). Issuing a fresh batch
  invalidates every code that came before it, including ones already used —
  ``RecoveryCode`` rows for the old batch are deleted outright rather than
  soft-deleted, on purpose (see the model docstring): a "restorable" MFA
  bypass would be a real vulnerability, not a convenience.

The pending-MFA sign-in state
------------------------------
ADR-05's login flow: a correct password does not call ``django.contrib.auth.
login`` when MFA applies. Instead the *session* — still anonymous, since
``login()`` was never called — gets one key, ``mfa_pending``, holding only a
user id and an expiry five minutes out. Every ordinary endpoint already
refuses that session: ``IsActiveUser`` checks ``request.user.is_authenticated``,
which is ``False`` until ``POST /auth/mfa/verify/`` succeeds and calls
``login()`` for real. Nothing had to be taught to recognise "pending" as a
special kind of forbidden — it already looks exactly like "not signed in",
because that is what it is.
"""

from __future__ import annotations

import re
import secrets
from datetime import timedelta
from hashlib import sha256
from io import BytesIO
from typing import Any

import pyotp
from cryptography.fernet import Fernet, InvalidToken
from django.conf import settings
from django.core.exceptions import ImproperlyConfigured
from django.core.exceptions import ValidationError as DjangoValidationError
from django.db import models, transaction
from django.utils import timezone
from django.utils.translation import gettext_lazy as _

from apps.audit.services import AuditAction, AuditResult, record
