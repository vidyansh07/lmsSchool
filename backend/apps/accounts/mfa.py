def _security_email(*, user, kind: str, title: str, body: str) -> None:
    """mfa.enrolled / mfa.disabled: informational, not a credential, so —
    unlike the OTP code itself — this goes through the ordinary notification
    outbox (``apps.notifications.services.notify``), the same as any other
    "something changed on your account" email.

    It must reach the user regardless of their notification preferences: a
    security event is not a subscription. ``NotificationCategory.SECURITY``
    has no matching ``email_*`` column on ``NotificationPreference`` — see
    that model's ``wants_email`` — so there is no toggle to bypass; the
    category simply never appears among the ones a preference can turn off.
    Only the institution-wide "email delivery" kill switch still applies,
    the same as it does to a locked-out admin's own broadcast — this is a
    channel-outage safeguard, not a per-user preference.
    """
    from apps.notifications.services import notify

    notify(recipient=user, kind=str(kind), title=title, body=body, send_email=True)


def start_enrolment(*, user) -> tuple[MfaDevice, str]:
    """Begin (or restart) TOTP enrolment. Returns the device row and the
    *raw* secret — the only moment it ever exists outside the encrypted
    column; the caller must return it in the response and hold it nowhere
    else (never logged, never audited — rule §13)."""
    existing = MfaDevice.objects.filter(user=user).first()
    if existing is not None and existing.is_confirmed:
        raise MfaEnrolmentConflict()

    secret = generate_totp_secret()
    encrypted = encrypt_secret(secret)
    if existing is not None:
        existing.secret_encrypted = encrypted
        existing.last_used_step = None
        existing.save(update_fields=["secret_encrypted", "last_used_step", "updated_at"])
        device = existing
    else:
        device = MfaDevice.objects.create(user=user, secret_encrypted=encrypted)
    return device, secret


@transaction.atomic
def confirm_enrolment(*, user, code: str) -> list[str]:
    """Prove possession of the enrolled secret; return ten recovery codes,
    shown exactly once (D-100's one-time-visibility spirit, same as an
    administrator's credential link)."""
    device = (
        MfaDevice.objects.select_for_update().filter(user=user, confirmed_at__isnull=True).first()
    )
    if device is None:
        raise MfaNoPendingEnrolment()

    secret = decrypt_secret(bytes(device.secret_encrypted))
    step = None if secret is None else _matched_step(secret=secret, code=code, last_used_step=None)
    if step is None:
        record(
            action=AuditAction.MFA_FAILED,
            actor=user,
            resource_type="mfa_device",
            resource_id=device.pk,
            result=AuditResult.FAILURE,
            context={"stage": "confirm"},
        )
        raise InvalidMfaCode()

    device.confirmed_at = timezone.now()
    device.last_used_step = step
    device.save(update_fields=["confirmed_at", "last_used_step", "updated_at"])

    codes = issue_recovery_codes(user=user)

    user.mfa_enrolled_at = timezone.now()
    user.save(update_fields=["mfa_enrolled_at"])

    record(
        action=AuditAction.MFA_CONFIRMED,
        actor=user,
        resource_type="mfa_device",
        resource_id=device.pk,
    )
    record(
        action=AuditAction.MFA_ENROLLED,
        actor=user,
        resource_type="mfa_device",
        resource_id=device.pk,
    )
    from apps.notifications.models import NotificationKind

    transaction.on_commit(
        lambda: _security_email(
            user=user,
            kind=NotificationKind.MFA_ENROLLED,
            title="Two-factor authentication turned on",
            body=(
                "An authenticator app was added to your account and ten recovery "
                "codes were issued. If this was not you, sign in and disable it, "
                "or contact your administrator immediately."
            ),
        )
    )
    return codes


def disable(*, user) -> None:
    """Remove the device and every recovery code — genuinely, not a soft
    delete (module docstring). Requires a fresh step-up; the caller (the
    view) checks that before calling this."""
    device = MfaDevice.objects.filter(user=user).first()
    if device is None:
        raise MfaNotEnabled()

    with transaction.atomic():
        device_id = device.pk
        device.delete()
        RecoveryCode.objects.filter(user=user).delete()
        user.mfa_enrolled_at = None
        user.save(update_fields=["mfa_enrolled_at"])
        record(
            action=AuditAction.MFA_DISABLED,
            actor=user,
            resource_type="mfa_device",
            resource_id=device_id,
        )
    from apps.notifications.models import NotificationKind

    transaction.on_commit(
        lambda: _security_email(
            user=user,
            kind=NotificationKind.MFA_DISABLED,
            title="Two-factor authentication turned off",
            body=(
                "Two-factor authentication was removed from your account, along "
                "with its recovery codes. If this was not you, contact your "
                "administrator immediately."
            ),
        )
    )


def regenerate_recovery_codes(*, user) -> list[str]:
    """Invalidate every existing recovery code and issue ten new ones.
    Requires a fresh step-up; the caller checks that before calling this."""
    if not has_confirmed_device(user=user):
        raise MfaNotEnabled()
    codes = issue_recovery_codes(user=user)
    record(
        action=AuditAction.MFA_RECOVERY_REGENERATED,
        actor=user,
        resource_type="user",
        resource_id=user.pk,
    )
    return codes


# ---------------------------------------------------------------------------
# "Is MFA required, and by what" — the login-time question
# ---------------------------------------------------------------------------


def has_confirmed_device(*, user) -> bool:
    return MfaDevice.objects.filter(user=user, confirmed_at__isnull=False).exists()


def _required_by_policy(*, user) -> bool:
    """Whether ``user``'s role is on the required list *and* their account
    is past its grace period.

    Grace-period anchor: the account's own ``date_joined``. This is a
    deliberate, narrow choice, made because ``DATA_MODEL.md`` allows exactly
    one new column on ``User`` for this phase (``mfa_enrolled_at``) — there
    is no second field free to record "when did the requirement start
    applying to this account". ``date_joined`` is the one timestamp every
    account already carries that is not itself evidence of enrolment, so a
    brand-new account gets a real `mfa.grace_days` window to enrol before
    its first login is forced into the pending-MFA branch, while an
    account that predates the policy is judged by its own age. The
    trade-off this accepts: turning `mfa_required_roles` on for a role does
    not itself re-arm a fresh grace window for that role's *existing*
    long-lived accounts — an admin account created two years ago is already
    past any `mfa.grace_days` value and is required immediately. That is
    consistent with treating the requirement as "how old must an account of
    this role be", not "how long since the policy last changed", which is
    both simpler and does not depend on when a policy row was last written
    (a value that resets to its default on `policy.reset` regardless of
    intent).
    """
    from apps.policies.resolver import policy

    required_roles = policy("authentication", "mfa_required_roles")
    if user.role not in required_roles:
        return False
    grace_days = policy("authentication", "mfa_grace_days")
    grace_until = user.date_joined + timedelta(days=grace_days)
    return timezone.now() >= grace_until


def is_required(*, user) -> bool:
    """Whether a correct password alone is enough, or MFA must follow."""
    return has_confirmed_device(user=user) or _required_by_policy(user=user)


def available_methods(*, user) -> list[str]:
    """Methods this user could complete a pending sign-in with, in the order
    the API always presents them: authenticator app first (the strongest and
    the one most people who have it will reach for), then email (always
    available to any active user), then recovery (only when unused codes
    remain)."""
    methods: list[str] = []
    if has_confirmed_device(user=user):
        methods.append(MfaMethod.TOTP)
    methods.append(MfaMethod.EMAIL)
    if RecoveryCode.objects.filter(user=user, used_at__isnull=True).exists():
        methods.append(MfaMethod.RECOVERY)
    return methods


